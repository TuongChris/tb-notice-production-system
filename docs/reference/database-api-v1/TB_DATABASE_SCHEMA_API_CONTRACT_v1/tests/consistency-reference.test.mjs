import test from 'node:test';
import assert from 'node:assert/strict';
import * as r from '../contracts/consistency-reference.mjs';
test('SHA-256 standard known ASCII vector',()=>assert.equal(r.exactTextSha256('abc'),'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'));
test('whitespace does not disappear',()=>assert.notEqual(r.exactTextSha256('a'),r.exactTextSha256('a ')));
test('line endings remain distinct',()=>assert.notEqual(r.exactTextSha256('a\nb'),r.exactTextSha256('a\r\nb')));
test('composed Unicode is not silently normalized',()=>assert.notEqual(r.exactTextSha256('é'),r.exactTextSha256('e\u0301')));
test('valid surrogate pair preserved',()=>assert.equal(r.assertUnicode('😀'),'😀'));
test('invalid high surrogate rejected',()=>assert.throws(()=>r.exactTextSha256('\ud800')));
test('invalid low surrogate rejected',()=>assert.throws(()=>r.exactTextSha256('\udfff')));
test('NUL rejected',()=>assert.throws(()=>r.exactTextSha256('a\0b')));
test('object order is deterministic',()=>assert.equal(r.canonicalSha256({b:2,a:1}),r.canonicalSha256({a:1,b:2})));
test('array order is retained',()=>assert.notEqual(r.canonicalSha256([1,2]),r.canonicalSha256([2,1])));
test('unsupported undefined rejected',()=>assert.throws(()=>r.canonicalJson({a:undefined})));
test('unsafe number rejected',()=>assert.throws(()=>r.canonicalJson(Number.MAX_SAFE_INTEGER+1)));
test('Date is not silently stringified',()=>assert.throws(()=>r.canonicalJson(new Date())));
test('duration over 24 hours supported',()=>assert.equal(r.parseMilliseconds('108000000'),108000000n));
test('duration zero is known zero',()=>assert.equal(r.parseMilliseconds('0'),0n));
test('null interval retains missingness',()=>assert.deepEqual(r.checkInterval(null,null),{start:null,end:null}));
test('negative duration rejected',()=>assert.throws(()=>r.parseMilliseconds('-1')));
test('leading zero rejected',()=>assert.throws(()=>r.parseMilliseconds('01')));
test('BigInt boundary protected',()=>assert.throws(()=>r.parseMilliseconds('9007199254740992')));
test('end before start rejected',()=>assert.throws(()=>r.checkInterval('30','29')));
test('equal endpoints rejected',()=>assert.throws(()=>r.checkInterval('30','30')));
test('same-case accepted',()=>assert.equal(r.sameCase('A',{caseId:'A'},{caseId:'A'}),true));
test('cross-case rejected',()=>assert.throws(()=>r.sameCase('A',{caseId:'B'})));
test('cross-agency rejected',()=>assert.throws(()=>r.sameAgency('A',{agencyId:'B'})));
test('controlled pending signature accepted',()=>assert.equal(r.requirePendingSignatureSlot('Name in identity\n'+r.PENDING_SIGNATURE),true));
test('missing pending slot rejected',()=>assert.throws(()=>r.requirePendingSignatureSlot('Signed Name')));
test('two signature slots rejected',()=>assert.throws(()=>r.requirePendingSignatureSlot(r.PENDING_SIGNATURE+'\n'+r.PENDING_SIGNATURE)));
